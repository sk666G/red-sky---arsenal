// Command moddocs generates docs/MODULES.md from the live registries.
//
// The core-side registry lives in package main of cmd/redsky-core, so it
// can't be imported as a library. We parse cmd/redsky-core/registry.go
// for the `Name:` and `Help:` fields inside regRegister(Module{...})
// blocks. The agent-side registry is imported directly via agentfw.
//
// Run `make docs` to regenerate.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/sk666G/red-sky---arsenal/internal/agentfw"
)

func main() {
	out, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "moddocs:", err)
		os.Exit(1)
	}
	dest := "docs/MODULES.md"
	if len(os.Args) > 1 {
		dest = os.Args[1]
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "moddocs:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(dest, []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "moddocs:", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d bytes)\n", dest, len(out))
}

type coreEntry struct {
	name string
	help string
}

func generate() (string, error) {
	entries, err := parseCoreRegistry("cmd/redsky-core/registry.go")
	if err != nil {
		return "", err
	}
	agent := agentfw.Names()

	var b strings.Builder
	b.WriteString("# RED SKY — Module Catalog\n\n")
	b.WriteString("_Generated by `cmd/moddocs` from the live registries. Do not edit by hand._\n\n")
	b.WriteString("Regenerate with:\n\n```\nmake docs\n```\n\n")

	// core table
	b.WriteString("## Core modules — `redsky-core -module <name>`\n\n")
	b.WriteString("These run on the operator box. Dispatch by name with JSON args:\n\n")
	b.WriteString("```\nredsky-core -module cloud -args '{\"action\":\"imds_probe\",\"provider\":\"aws\"}'\n```\n\n")
	b.WriteString("List with `redsky-core -module-help`.\n\n")
	b.WriteString(fmt.Sprintf("**%d modules.**\n\n", len(entries)))
	b.WriteString("| Name | Help |\n|------|------|\n")
	for _, e := range entries {
		b.WriteString(fmt.Sprintf("| `%s` | %s |\n", e.name, escapeCell(e.help)))
	}
	b.WriteString("\n")

	// agent table
	b.WriteString("## Agent modules — `Task.Kind=\"framework\"`, `Task.Cmd=<name>`\n\n")
	b.WriteString("These run inside the agent process. Dispatched by `agentfw.Dispatch(ctx, name, args)`.\n\n")
	b.WriteString(fmt.Sprintf("**%d modules.**\n\n", len(agent)))
	if len(agent) == 0 {
		b.WriteString("_(none registered)_\n\n")
	} else {
		b.WriteString("| Name |\n|------|\n")
		for _, n := range agent {
			b.WriteString(fmt.Sprintf("| `%s` |\n", n))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Adding a module\n\n")
	b.WriteString("**Core:** add a `regRegister(Module{Name: \"...\", Help: \"...\", Run: ...})` call inside an `init()` in `cmd/redsky-core/registry.go`. Run `make docs`.\n\n")
	b.WriteString("**Agent:** drop a new file in `internal/agentfw/` that calls `Register()` from `init()`. Run `make docs`.\n")

	return b.String(), nil
}

// parseCoreRegistry reads cmd/redsky-core/registry.go and returns every
// (Name, Help) pair from a regRegister(Module{...}) block, sorted by name.
func parseCoreRegistry(path string) ([]coreEntry, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	lines := strings.Split(string(data), "\n")

	var entries []coreEntry
	var pending coreEntry
	for _, raw := range lines {
		line := strings.TrimSpace(raw)
		switch {
		case strings.HasPrefix(line, "Name:"):
			if v, ok := goStringLit(line[len("Name:"):]); ok {
				pending.name = v
			}
		case strings.HasPrefix(line, "Help:"):
			if v, ok := goStringLit(line[len("Help:"):]); ok {
				pending.help = v
			}
		}
		if pending.name != "" && pending.help != "" {
			entries = append(entries, pending)
			pending = coreEntry{}
		}
	}
	if len(entries) == 0 {
		return nil, fmt.Errorf("no modules parsed from %s", path)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].name < entries[j].name })
	return entries, nil
}

// goStringLit parses a Go double-quoted or backtick string literal from
// the start of s. Returns the unquoted content. Never panics; returns
// ("", false) on malformed input.
func goStringLit(s string) (string, bool) {
	s = strings.TrimSpace(s)
	if len(s) < 2 {
		return "", false
	}
	switch s[0] {
	case '"':
		for i := 1; i < len(s); i++ {
			if s[i] == '\\' {
				i++
				continue
			}
			if s[i] == '"' {
				return s[1:i], true
			}
		}
	case '`':
		for i := 1; i < len(s); i++ {
			if s[i] == '`' {
				return s[1:i], true
			}
		}
	}
	return "", false
}

func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}
